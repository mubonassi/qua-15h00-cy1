#Array - Lista de Dados

listaS = ["a","b","c","d","e","f"] #Lista/Array de Strings
listaI = [1,2,3,4,5,6,7,8,9] #Lista de Int
listaM = [1,"a",2,"b",True,10.9,10+2] #Lista Mista

#Exibir a Lista
print(f"Lista String: {listaS}")
print(f"Lista Int: {listaI}")
print(f"Lista Mista: {listaM}")

#Exibir um item (index) especifico
print(f"Exibindo o Item 1 da Lista S: {listaS[0]}")
print(f"Exibindo o Item 6 da Lista I: {listaI[5]}")
print(f"Exibindo qualquer Item da Lista M: {listaM[4]}")